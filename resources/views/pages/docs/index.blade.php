        <h1>Introduction</h1>

        <p>Spectacular helps teams work around a living functional specification: a clear, structured description of what the software should do, who it is for, what is still unknown, and what work remains before it can be shipped.</p>

        <p>Slack, Jira, Confluence, etc. are great tools, but requirements can be scattered amongst threads, tickets, and emails. Too often, developers (and now AI agents) are expected to infer requirements from these fragments, which leads to misinterpretation and churn.</p>

        <p>Spectacular gives requirements a single home everyone can work from.</p>

        <p>Instead of treating the specification as a document you write once and forget, Spectacular treats it as an active part of the delivery process. As the project changes, the specification changes with it. This is not waterfall; requirements can and should be clarified, discussed, and revisited through to development and beyond.</p>

        <p>Use Spectacular when you want an answer to the question: What are we building, exactly?</p>

        <h2 id="who-is-spectacular-for">Who is Spectacular for?</h2>

        <p>Spectacular is designed for software teams that want a clearer bridge between product intent and implementation.</p>

        <p>It is especially useful for:</p>
        <ul>
            <li><strong>Founders</strong> turning product ideas into build-ready plans</li>
            <li><strong>Product managers</strong> writing clearer specifications for engineers</li>
            <li><strong>Engineering leads</strong> reducing ambiguity before implementation starts</li>
            <li><strong>Agencies</strong> turning client discovery into agreed scope</li>
            <li><strong>AI-native teams</strong> that need structured context for coding assistants and agents</li>
        </ul>

        <p>Spectacular is not trying to replace every project management, documentation, or issue tracking tool. It is narrower than that. It is the place where the specification lives.</p>

        <h2 id="methodology">Methodology</h2>

        <p>The specification is to act as the single source of truth. It is a living document that must be maintained. If it's not in the specification, it shouldn't get built. You can still use GitHub Issues, Linear, Jira, Slack, Notion, etc., but newly discovered requirements must feed back into the specification.</p>

        <p>Before writing requirements, identify the people or systems involved. Then describe the features those users need. Only then break each feature into requirements.</p>

        <p>A good workflow is:</p>
        <ol>
            <li>Create a project for the product or next major release</li>
            <li>Identify the users or systems that will interact with the product</li>
            <li>Define the major features of the product</li>
            <li>Break each feature into requirements (user stories)</li>
            <li>Capture unknowns where further discovery is required</li>
            <li>Invite collaborators to provide feedback, estimate effort and update progress</li>
            <li>Maintain the document throughout development and beyond.</li>
        </ol>

        <p>The goal is not to create an impressive document. The goal is to create a specification that is complete, unambigous and suitable for all involved.</p>

        <h2 id="ai-assisted-development">Spectacular and AI-assisted development</h2>

        <p>AI coding tools are most useful when they are given clear, structured context. Agents struggle and hallucinate intent without clear instructions leading to frustration and burning tokens unnecessarily. The explicit and structured specification provided by Spectacular help these agents make informed decisions.</p>

        <p>Vague prompts produces vague software. A clear specification gives both people and AI something trustworthy to build from.</p>
