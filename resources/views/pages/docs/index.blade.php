        <h2 id="what-spectacular-is">What Spectacular is</h2>
        <p>Spectacular is a functional specification builder. It gives a product or project team one structured place to define users, features, requirements, tasks, unknowns, estimates, feedback, and exports.</p>
        <p>The goal is not to replace judgement with process. The goal is to keep the specification clear enough for stakeholders to review, detailed enough for implementation, and structured enough to remain useful as the product changes.</p>

        <h2 id="documentation-organisation">How the documentation is organised</h2>
        <p>The documentation follows the same path a new team usually takes: understand the method, choose Cloud or self-hosting, create projects, model users and features, write requirements, then collaborate with roles and invitations.</p>

        <h2 id="methodology">Methodology</h2>
        <p>Spectacular treats the specification as the durable source of product intent, not as a one-off document written before development begins. Start with behaviour, make uncertainty visible, keep implementation close to the requirement, and maintain the spec as the product changes.</p>
