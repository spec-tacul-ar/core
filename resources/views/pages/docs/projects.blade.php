        <h2 id="creating-projects">Creating projects</h2>
        <p>Start with a clear working title, then add the main user types and feature areas. The first pass should create a useful outline, not a finished specification.</p>

        <h2 id="organising">Organising</h2>
        <p>The organise panel lets editors reorder users, features, and requirements. Use this to make the specification read naturally: foundational concepts first, core workflows next, edge cases and administration later.</p>

        <h2 id="exporting">Exporting</h2>
        <p>Projects can be exported as HTML, Markdown, or JSON. HTML is best for review, Markdown is useful for repositories and documents, and JSON is useful for integrations or automation.</p>

        <h2 id="deleting">Deleting</h2>
        <p>Deleting a project removes the specification and its related content. Treat deletion as an administrative action and export or back up anything that needs to be retained.</p>
