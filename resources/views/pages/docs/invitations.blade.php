        <h2 id="sending-invitations">Sending invitations</h2>
        <p>Project owners can invite collaborators from the People panel. Enter an email address, choose a role, and send the invitation.</p>

        <h2 id="accepting-invitations">Accepting invitations</h2>
        <p>Invited users see pending invitations from the projects screen. If email verification is required, they must verify their account before accepting.</p>

        <h2 id="managing-invitations">Managing invitations</h2>
        <p>Pending invitations can be removed by an owner. Remove invitations when access is no longer needed or when an email address was entered incorrectly.</p>

        <h2 id="choosing-the-right-role">Choosing the right role</h2>
        <p>Invite the smallest role that fits the person’s job. Use Viewer for review, Editor for specification work, and Owner only for people who should administer the project.</p>
