            <p class="max-w-2xl text-lg leading-8 text-gray-500">Roles control what collaborators can do inside a project.</p>
        </header>

        <h2 id="owner">Owner</h2>
        <p>Owners can do everything in a project, including editing the specification, inviting collaborators, changing roles, exporting, and deleting the project.</p>

        <h2 id="editor">Editor</h2>
        <p>Editors can view and edit the specification. Use this role for people responsible for shaping requirements, tasks, unknowns, and project structure.</p>

        <h2 id="viewer">Viewer</h2>
        <p>Viewers can read the project and leave feedback. Use this role for stakeholders, reviewers, or clients who should participate without changing the specification directly.</p>

        <h2 id="leaving-a-project">Leaving a project</h2>
        <p>Collaborators can leave a project. Owners can leave only when another owner remains, preventing a project from being left without an administrator.</p>
