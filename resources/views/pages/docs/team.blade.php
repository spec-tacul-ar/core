        <h1>Team</h1>

        <p>If you're not running Spectacular in solo mode, you can invite others to collaborate on your project.</p>

        <h2 id="roles">Roles</h2>

        <p>Role-based access control is available for when you want to collaborate with others.</p>

        <h3>Owners</h3>
        <p>Owners can do everything in a project, including editing the specification, inviting collaborators, changing roles, exporting, archiving, restoring, and deleting the project. This role is occupied by product owners and project managers.</p>

        <p>There must be at least one owner per project. Creating a project automatically sets you as the owner. Owners can remove other owners if they were added to the project after them.</p>

        <h3>Editors</h3>
        <p>Editors can view and edit the specification. Developers are a good fit for this role as it lets them update progress, block requirements and create unknowns.</p>

        <h3>Viewers</h3>
        <p>Viewers can read the project and leave feedback. Use this role for stakeholders, reviewers, or clients who should participate without changing the specification directly.</p>

        <h2 id="invitations">Invitations</h2>

        <p>Project owners can invite collaborators from the team panel. Enter an email address, choose a role, and send the invitation. Invitees will receive an email inviting them to join the project or register for an account if they don't already have one. Their invitation will be waiting for them when they first log in.</p>

        <p>Pending invitations can be revoked at any time by the owners. Remove invitations when access is no longer needed or when an email address was entered incorrectly.</p>

        <h2 id="leaving">Leaving a project</h2>
        <p>Collaborators can leave a project via the team panel. Owners can leave only when another owner remains, preventing a project from being left without someone in charge.</p>
